<?php
/**
 * WordPress Address and Site Address.
 *
 * @package UnstoppableSolutions\MigrationInspector
 */

namespace UnstoppableSolutions\MigrationInspector\Scanner\Checks;

use UnstoppableSolutions\MigrationInspector\Scanner\Check;
use UnstoppableSolutions\MigrationInspector\Scanner\Db_Info;
use UnstoppableSolutions\MigrationInspector\Scanner\Finding;
use UnstoppableSolutions\MigrationInspector\Scanner\Location;
use UnstoppableSolutions\MigrationInspector\Scanner\Scan_Context;
use UnstoppableSolutions\MigrationInspector\Scanner\Severity;

defined( 'ABSPATH' ) || exit;

/**
 * Compares home and siteurl, constants that override them, and the address
 * the scan was started from.
 */
final class Site_Url_Check extends Check {

	/**
	 * Key.
	 *
	 * @return string
	 */
	public function key() {
		return 'site_urls';
	}

	/**
	 * Category.
	 *
	 * @return string
	 */
	public function category() {
		return 'urls';
	}

	/**
	 * Label.
	 *
	 * @return string
	 */
	public function label() {
		return __( 'WordPress Address and Site Address', 'unstoppable-migration-inspector' );
	}

	/**
	 * Kinds.
	 *
	 * @return array<string, array{severity: string, title: string, explanation: string, action: string}>
	 */
	public function kinds() {
		return array(
			'host_mismatch'     => array(
				'severity'    => Severity::WARNING,
				'title'       => __( 'WordPress Address and Site Address use different domains', 'unstoppable-migration-inspector' ),
				'explanation' => __( 'The WordPress Address (where WordPress files live) and the Site Address (what visitors use) point to different domains. After a move this usually means one of them still has the old domain, which breaks logins, redirects or the admin area.', 'unstoppable-migration-inspector' ),
				'action'      => __( 'Open Settings > General and make both addresses use the current domain. If the fields are greyed out, they are set in wp-config.php (WP_HOME and WP_SITEURL); change them there.', 'unstoppable-migration-inspector' ),
			),
			'scheme_mismatch'   => array(
				'severity'    => Severity::WARNING,
				'title'       => __( 'One address uses HTTPS and the other does not', 'unstoppable-migration-inspector' ),
				'explanation' => __( 'Mixing http:// and https:// between the WordPress Address and the Site Address causes redirect loops, login cookie problems and mixed-content warnings.', 'unstoppable-migration-inspector' ),
				'action'      => __( 'Use https:// for both addresses if the site has a working SSL certificate (Settings > General, or WP_HOME and WP_SITEURL in wp-config.php).', 'unstoppable-migration-inspector' ),
			),
			'constant_override' => array(
				'severity'    => Severity::NOTICE,
				'title'       => __( 'An address is forced in wp-config.php and differs from the database', 'unstoppable-migration-inspector' ),
				'explanation' => __( 'WP_HOME or WP_SITEURL in wp-config.php overrides the address stored in the database, which still holds a different value. The site works now, but if the constant is removed later (for example by a new host\'s config file) the old address comes back.', 'unstoppable-migration-inspector' ),
				'action'      => __( 'Keep the constant, or update the stored address to match it so the two agree. Search & Replace on the options table, or WP-CLI "wp option update home", can do this.', 'unstoppable-migration-inspector' ),
			),
			'request_mismatch'  => array(
				'severity'    => Severity::NOTICE,
				'title'       => __( 'You are using the site from a different address', 'unstoppable-migration-inspector' ),
				'explanation' => __( 'This scan was started from an address that is not the Site Address. That is normal while testing a move on a temporary URL, but links generated by WordPress will point to the Site Address, not to the address in your browser.', 'unstoppable-migration-inspector' ),
				'action'      => __( 'If the site has now moved for good, make sure the Site Address is the address visitors will use. Otherwise no action is needed.', 'unstoppable-migration-inspector' ),
			),
		);
	}

	/**
	 * Run.
	 *
	 * @param Scan_Context $context Context.
	 * @return Finding[]
	 */
	public function run( Scan_Context $context ) {
		$home     = (string) $context->get( 'home' );
		$siteurl  = (string) $context->get( 'siteurl' );
		$findings = array();

		$home_host = Location::host( Location::from_url( $home ) );
		$site_host = Location::host( Location::from_url( $siteurl ) );

		if ( '' !== $home_host && '' !== $site_host && $home_host !== $site_host ) {
			$findings[] = ( new Finding( 'host_mismatch', $home_host . ' / ' . $site_host ) )->on( 'setting', 'home', 'siteurl' );
		}

		$home_https = 0 === strpos( strtolower( $home ), 'https://' );
		$site_https = 0 === strpos( strtolower( $siteurl ), 'https://' );

		if ( $home_https !== $site_https ) {
			$findings[] = ( new Finding( 'scheme_mismatch', ( $home_https ? 'https' : 'http' ) . ' / ' . ( $site_https ? 'https' : 'http' ) ) )->on( 'setting', 'home', 'siteurl' );
		}

		foreach ( array(
			'home'    => 'WP_HOME',
			'siteurl' => 'WP_SITEURL',
		) as $option => $constant ) {
			if ( ! defined( $constant ) ) {
				continue;
			}

			$stored = Db_Info::raw_option( $option );

			if ( null !== $stored && untrailingslashit( strtolower( $stored ) ) !== untrailingslashit( strtolower( (string) constant( $constant ) ) ) ) {
				$findings[] = ( new Finding( 'constant_override', $constant ) )
					->on( 'setting', $option )
					->with( array( 'stored_host' => Location::host( Location::from_url( $stored ) ) ) );
			}
		}

		$request = (string) $context->get( 'request_host', '' );

		if ( '' !== $request && '' !== $home_host && $request !== $home_host ) {
			$findings[] = ( new Finding( 'request_mismatch', $request ) )->on( 'setting', 'home' );
		}

		return $findings;
	}
}
